! ============================================================================
!  FPMP Host Fortran Benchmark — Accuracy Sum
!
!  Purpose
!  -------
!  Measures both ACCURACY and THROUGHPUT of recursive summation across four
!  accumulator types over a large array of mantissa-rich, pseudo-random
!  single-precision inputs.
!
!    Accumulator           Mantissa bits   Format
!    -------------------   -------------   ------------------
!    real(real32)           23             native single
!    real(real64)           52             native double
!    type(fp32mp2)         ~46             FPMP float-float
!    type(fp64mp2)        ~106             FPMP double-double
!
!  Two algorithms are run, both over the SAME input array:
!
!    Mode 1: serial accumulation
!      One register accumulator, `N` rounding-prone adds.  This is the
!      natural Fortran loop and exposes each accumulator's mantissa width
!      directly.
!
!    Mode 2: device-style blocked reduction
!      Mimics the GPU benchmark on the host: a grid-stride loop produces
!      `NUM_BLOCKS * BLOCK_SIZE` per-thread partials, a per-block tree
!      reduction collapses to one fp64 partial per block, then the final
!      `NUM_BLOCKS`-element fp64 sum runs on the host.  The accumulator
!      chain length collapses from `N` to about `N/(NUM_BLOCKS*BLOCK_SIZE)
!      + log2(BLOCK_SIZE)`, which is why the GPU benchmark reports zero
!      error for every accumulator above fp32 with the default geometry.
!
!  Workload
!  --------
!  Inputs `x(i)` are deterministic pseudo-random fp32 values in
!  [0, 2^SCALE_BITS), generated by taking the fractional part of `i * φ`
!  (golden-ratio low-discrepancy sequence) and scaling.  Each input has the
!  full 23 bits of fp32 mantissa populated.
!
!  Reference
!  ---------
!  The reference sum is computed in fp64mp2 (~106-bit mantissa) using the
!  serial loop.  Every other accumulator's error is reported relative to
!  this value.
!
!  Origin
!  ------
!  Inspired by a customer-supplied Fortran example (accuracy_sum.f90).
!  Showcases the defined assignment(=) and mixed-type operator overloads
!  added to the Fortran bindings — the inner loop is `acc = acc + x(i)`
!  for every accumulator type, with no explicit casts.
!
!  Usage
!  -----
!  Compile-time controls (override on the make command line):
!      -DN_ELEMENTS=<int>   default: 10000000
!      -DN_REPS=<int>       default: 5
!      -DSCALE_BITS=<int>   default: 0  (max input ≈ 2^0)
!      -DBLOCK_SIZE=<int>   default: 256   (Mode 2 only)
!      -DNUM_BLOCKS=<int>   default: 1024  (Mode 2 only)
! ============================================================================

#ifndef N_ELEMENTS
#define N_ELEMENTS 10000000
#endif

#ifndef N_REPS
#define N_REPS 5
#endif

#ifndef SCALE_BITS
#define SCALE_BITS 0
#endif

#ifndef BLOCK_SIZE
#define BLOCK_SIZE 256
#endif

#ifndef NUM_BLOCKS
#define NUM_BLOCKS 1024
#endif

program fortran_sum_host
  use, intrinsic :: iso_fortran_env
  use fpmp_api
  implicit none

  integer, parameter :: N    = N_ELEMENTS
  integer, parameter :: REPS = N_REPS
  integer, parameter :: BLK  = BLOCK_SIZE
  integer, parameter :: NB   = NUM_BLOCKS
  integer, parameter :: NTH  = BLK * NB

  ! Golden-ratio low-discrepancy sequence multiplier (φ - 1).
  real(real64), parameter :: PHI   = 0.6180339887498948_real64
  real(real64), parameter :: SCALE = 2.0_real64**SCALE_BITS

  real(real32), allocatable :: x(:)
  real(real64) :: ref_sum, mode2_ref, t0, t1, dt_min, u, total
  integer      :: rep, i, b, t, stride, gid

  real(real32)  :: acc32
  real(real64)  :: acc64
  type(fp32mp2) :: acc_ff
  type(fp64mp2) :: acc_dd

  ! Per-block scratch for Mode 2 (heap to stay safe at large BLOCK_SIZE).
  real(real32),  allocatable :: pt32(:)
  real(real64),  allocatable :: pt64(:)
  type(fp32mp2), allocatable :: ptff(:)
  type(fp64mp2), allocatable :: ptdd(:)
  real(real64),  allocatable :: bp(:)

  ! Per-accumulator results (filled by each timed block, printed in one
  ! pass per mode).  Splitting timing from printing lets every row
  ! reference dt_fp64 for the "Speedup vs real64" column without forcing
  ! the real64 row to run first.  Reused between Mode 1 and Mode 2.
  real(real64) :: got_fp32, got_fp64, got_fp32mp2, got_fp64mp2
  real(real64) :: dt_fp32,  dt_fp64,  dt_fp32mp2,  dt_fp64mp2

  ! ------------------------------------------------------------------------
  ! Generate input
  ! ------------------------------------------------------------------------
  allocate(x(N))
  do i = 1, N
    u    = modulo(real(i, real64) * PHI, 1.0_real64)
    x(i) = real(u * SCALE, real32)
  end do

  ! Reference: serial fp64mp2 sum (~106-bit mantissa).
  acc_dd = 0.0_c_float
  do i = 1, N
    acc_dd = acc_dd + x(i)
  end do
  ref_sum = fpmp_to_double(acc_dd)

  print '(A)',         '======================================================================================'
  print '(A)',         '  FPMP Host Fortran Benchmark — Accuracy Sum'
  print '(A)',         '======================================================================================'
  print '(A,I0)',      '  N            = ', N
  print '(A,I0)',      '  repetitions  = ', REPS
  print '(A,I0,A,ES10.3)', '  scale        = 2^', SCALE_BITS, ' = ', SCALE
  print '(A)',         '  inputs       = pseudo-random fp32 in [0, scale) (golden-ratio LDS)'
  print '(A)',         '  reference    = sum(x) in fp64mp2 (~106-bit mantissa)'
  print '(A,ES22.15)', '  reference    = ', ref_sum

  ! ========================================================================
  ! Mode 1 — serial accumulation over the full N
  ! ========================================================================
  print '(A)', '--------------------------------------------------------------------------------------'
  print '(A)', '  Mode 1: serial accumulation (acc = acc + x(i)) over the full N'
  print '(A)', '          one accumulator, N rounding-prone adds'
  print '(A)', '--------------------------------------------------------------------------------------'
  print '(A)', '  Accumulator       |Error|     Rel.Err  Throughput        Time     Speedup'
  print '(A)', '                                         (Melem/s)         (s)   vs real64'
  print '(A)', '  -------------  ----------  ----------  ----------  ----------  ----------'

  ! 1.1 real32
  dt_min = huge(dt_min)
  do rep = 1, REPS
    acc32 = 0.0_real32
    call cpu_time(t0)
    do i = 1, N
      acc32 = acc32 + x(i)
    end do
    call cpu_time(t1)
    dt_min = min(dt_min, t1 - t0)
  end do
  got_fp32 = real(acc32, real64)
  dt_fp32  = dt_min

  ! 1.2 real64
  dt_min = huge(dt_min)
  do rep = 1, REPS
    acc64 = 0.0_real64
    call cpu_time(t0)
    do i = 1, N
      acc64 = acc64 + real(x(i), real64)
    end do
    call cpu_time(t1)
    dt_min = min(dt_min, t1 - t0)
  end do
  got_fp64 = acc64
  dt_fp64  = dt_min

  ! 1.3 fp32mp2
  dt_min = huge(dt_min)
  do rep = 1, REPS
    acc_ff = 0.0_c_float
    call cpu_time(t0)
    do i = 1, N
      acc_ff = acc_ff + x(i)
    end do
    call cpu_time(t1)
    dt_min = min(dt_min, t1 - t0)
  end do
  got_fp32mp2 = fpmp_to_double(acc_ff)
  dt_fp32mp2  = dt_min

  ! 1.4 fp64mp2 — re-time the reference accumulator (error is 0 by construction).
  dt_min = huge(dt_min)
  do rep = 1, REPS
    acc_dd = 0.0_c_float
    call cpu_time(t0)
    do i = 1, N
      acc_dd = acc_dd + x(i)
    end do
    call cpu_time(t1)
    dt_min = min(dt_min, t1 - t0)
  end do
  got_fp64mp2 = fpmp_to_double(acc_dd)
  dt_fp64mp2  = dt_min

  call print_table(ref_sum)

  ! ========================================================================
  ! Mode 2 — device-style blocked reduction (mimics the CUDA kernels)
  !
  ! Mode 2 uses a SEPARATE reference: the same blocked algorithm run with
  ! an fp64mp2 accumulator.  This mirrors the device benchmark, which
  ! uses its own fp64mp2 kernel result as the reference, and removes the
  ! cross-algorithm rounding offset (~ulp_fp64(reference)) that would
  ! otherwise appear as a precision floor for every accumulator above
  ! fp32 in this mode.
  ! ========================================================================
  allocate(pt32(BLK), pt64(BLK), ptff(BLK), ptdd(BLK), bp(NB))

  ! Compute mode2_ref: blocked fp64mp2 reduction (no timing).
  do b = 1, NB
    do t = 1, BLK
      gid = (b-1)*BLK + t
      ptdd(t) = 0.0_c_float
      i = gid
      do while (i <= N)
        ptdd(t) = ptdd(t) + x(i)
        i = i + NTH
      end do
    end do
    stride = BLK / 2
    do while (stride > 0)
      do t = 1, stride
        ptdd(t) = ptdd(t) + ptdd(t + stride)
      end do
      stride = stride / 2
    end do
    bp(b) = fpmp_to_double(ptdd(1))
  end do
  mode2_ref = 0.0_real64
  do b = 1, NB
    mode2_ref = mode2_ref + bp(b)
  end do

  print '(A)', '--------------------------------------------------------------------------------------'
  print '(A,I0,A,I0,A,I0,A)', &
        '  Mode 2: device-style blocked reduction (NUM_BLOCKS=', NB, &
        ', BLOCK_SIZE=', BLK, ', threads=', NTH, ')'
  print '(A)', '          per-thread grid-stride + per-block tree + fp64 final sum'
  print '(A,I0,A)', '          ~', N/NTH, &
        ' adds per "thread", log2(BLOCK_SIZE) tree adds, NUM_BLOCKS final fp64 adds'
  print '(A,ES22.15)', '          mode2 reference (blocked fp64mp2)  = ', mode2_ref
  print '(A,ES10.3)',  '          |mode2_ref - serial fp64mp2 ref|   = ', &
        abs(mode2_ref - ref_sum)
  print '(A)', '--------------------------------------------------------------------------------------'
  print '(A)', '  Accumulator       |Error|     Rel.Err  Throughput        Time     Speedup'
  print '(A)', '                                         (Melem/s)         (s)   vs real64'
  print '(A)', '  -------------  ----------  ----------  ----------  ----------  ----------'

  ! 2.1 blocked fp32
  dt_min = huge(dt_min)
  do rep = 1, REPS
    call cpu_time(t0)
    do b = 1, NB
      do t = 1, BLK
        gid = (b-1)*BLK + t
        pt32(t) = 0.0_real32
        i = gid
        do while (i <= N)
          pt32(t) = pt32(t) + x(i)
          i = i + NTH
        end do
      end do
      stride = BLK / 2
      do while (stride > 0)
        do t = 1, stride
          pt32(t) = pt32(t) + pt32(t + stride)
        end do
        stride = stride / 2
      end do
      bp(b) = real(pt32(1), real64)
    end do
    total = 0.0_real64
    do b = 1, NB
      total = total + bp(b)
    end do
    call cpu_time(t1)
    dt_min = min(dt_min, t1 - t0)
  end do
  got_fp32 = total
  dt_fp32  = dt_min

  ! 2.2 blocked fp64
  dt_min = huge(dt_min)
  do rep = 1, REPS
    call cpu_time(t0)
    do b = 1, NB
      do t = 1, BLK
        gid = (b-1)*BLK + t
        pt64(t) = 0.0_real64
        i = gid
        do while (i <= N)
          pt64(t) = pt64(t) + real(x(i), real64)
          i = i + NTH
        end do
      end do
      stride = BLK / 2
      do while (stride > 0)
        do t = 1, stride
          pt64(t) = pt64(t) + pt64(t + stride)
        end do
        stride = stride / 2
      end do
      bp(b) = pt64(1)
    end do
    total = 0.0_real64
    do b = 1, NB
      total = total + bp(b)
    end do
    call cpu_time(t1)
    dt_min = min(dt_min, t1 - t0)
  end do
  got_fp64 = total
  dt_fp64  = dt_min

  ! 2.3 blocked fp32mp2
  dt_min = huge(dt_min)
  do rep = 1, REPS
    call cpu_time(t0)
    do b = 1, NB
      do t = 1, BLK
        gid = (b-1)*BLK + t
        ptff(t) = 0.0_c_float
        i = gid
        do while (i <= N)
          ptff(t) = ptff(t) + x(i)
          i = i + NTH
        end do
      end do
      stride = BLK / 2
      do while (stride > 0)
        do t = 1, stride
          ptff(t) = ptff(t) + ptff(t + stride)
        end do
        stride = stride / 2
      end do
      bp(b) = fpmp_to_double(ptff(1))
    end do
    total = 0.0_real64
    do b = 1, NB
      total = total + bp(b)
    end do
    call cpu_time(t1)
    dt_min = min(dt_min, t1 - t0)
  end do
  got_fp32mp2 = total
  dt_fp32mp2  = dt_min

  ! 2.4 blocked fp64mp2
  dt_min = huge(dt_min)
  do rep = 1, REPS
    call cpu_time(t0)
    do b = 1, NB
      do t = 1, BLK
        gid = (b-1)*BLK + t
        ptdd(t) = 0.0_c_float
        i = gid
        do while (i <= N)
          ptdd(t) = ptdd(t) + x(i)
          i = i + NTH
        end do
      end do
      stride = BLK / 2
      do while (stride > 0)
        do t = 1, stride
          ptdd(t) = ptdd(t) + ptdd(t + stride)
        end do
        stride = stride / 2
      end do
      bp(b) = fpmp_to_double(ptdd(1))
    end do
    total = 0.0_real64
    do b = 1, NB
      total = total + bp(b)
    end do
    call cpu_time(t1)
    dt_min = min(dt_min, t1 - t0)
  end do
  got_fp64mp2 = total
  dt_fp64mp2  = dt_min

  call print_table(mode2_ref)

  print '(A)', '======================================================================================'

  deallocate(pt32, pt64, ptff, ptdd, bp, x)

contains

  ! Print all four rows for a single mode in one pass, including the
  ! "Speedup vs real64" column (dt_fp64 / dt_this_row).  Splitting
  ! print from time collection lets every row reference dt_fp64 even
  ! though the real32 row runs first.  Numeric columns are uniform
  ! ES10.3 with two-space gutters (error, throughput, time); the
  ! speedup column uses F10.3 so the typical O(0.1)..O(10) ratios read
  ! cleanly without exponent noise.  Units (Melem/s, s, "vs real64")
  ! live in the header sub-line.
  subroutine print_table(ref)
    real(real64), intent(in) :: ref
    call print_row('real(real32) ', got_fp32,    ref, dt_fp32   )
    call print_row('real(real64) ', got_fp64,    ref, dt_fp64   )
    call print_row('type(fp32mp2)', got_fp32mp2, ref, dt_fp32mp2)
    call print_row('type(fp64mp2)', got_fp64mp2, ref, dt_fp64mp2)
  end subroutine print_table

  ! All callers pass a 13-character `label`, so `A` (no width) prints
  ! it left-justified in the column without the extra leading space
  ! that `A14` would insert.
  subroutine print_row(label, got, ref, dt)
    character(len=*), intent(in) :: label
    real(real64),     intent(in) :: got, ref, dt
    real(real64) :: err, rel, melem_per_s, speedup
    err         = abs(got - ref)
    rel         = err / max(abs(ref), 1.0e-300_real64)
    melem_per_s = real(N, real64) / max(dt, 1.0e-12_real64) * 1.0e-6_real64
    speedup     = dt_fp64 / max(dt, 1.0e-12_real64)
    print '(2X,A,2X,ES10.3,2X,ES10.3,2X,ES10.3,2X,ES10.3,2X,F10.3)', &
      label, err, rel, melem_per_s, dt, speedup
  end subroutine print_row

end program fortran_sum_host
